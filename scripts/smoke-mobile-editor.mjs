import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const app=fs.readFileSync(new URL('../private/app-v6.8.html.txt',import.meta.url),'utf8');
const script=app.match(/<script>([\s\S]*?)<\/script>/)[1];
new Function(script);
const start=script.indexOf('const mobileQuery=');
const end=script.lastIndexOf('mobileInstall();');
const nodes=new Map();
const node=()=>({textContent:'',value:'',disabled:false});
for(const id of ['mobileScrub','mobileTime','mobilePlay','mobileMove','mobileContext'])nodes.set('#'+id,node());
const calls=[];
const context={window:{},matchMedia:()=>({matches:true}),$:s=>nodes.get(s),ui:{playhead:2,selectedType:'player',selectedId:'p1',playing:false},state:{timeline:{duration:12,movements:[]}},playerById:id=>({id,name:'Player 1'}),fmtTime:n=>String(n),toast:s=>calls.push(s),v7DeleteEquipment:id=>calls.push(['equipment',id]),returnToBench:id=>calls.push(['bench',id]),renderAll:()=>calls.push('render'),document:{createElement:()=>({})}};
vm.createContext(context);vm.runInContext(script.slice(start,end),context);
vm.runInContext('mobileSync()',context);
assert.equal(nodes.get('#mobileScrub').value,2);assert.equal(nodes.get('#mobileScrub').max,12);
assert.match(nodes.get('#mobileContext').textContent,/Player 1/);
context.ui.selectedType='puck';vm.runInContext('mobileSync()',context);
assert.equal(nodes.get('#mobileMove').disabled,false,'Puck actions must remain accessible without a selected skater');
context.ui.selectedType='equipment';context.ui.selectedId='cone';vm.runInContext('mobileDelete()',context);
assert.equal(calls[0][0],'equipment');assert.equal(calls[0][1],'cone');
context.ui.selectedType='player';context.ui.selectedId='p1';vm.runInContext('mobileDelete()',context);
assert.equal(calls[2][0],'bench');
context.ui.selectedType='clip';context.ui.selectedId='route';context.state.timeline.movements=[{id:'route',playerId:'p2'}];assert.equal(vm.runInContext('mobileSelectedPlayer()',context),'p2');
await vm.runInContext('mobileExportVideo()',context);
assert.match(calls.at(-1),/unavailable/,'Unsupported export must return a usable message');
console.log('Mobile runtime checks passed: scrubber, selection, puck actions, deletion, and unsupported export.');
